#!/usr/bin/env node
// scripts/build-client.mjs
//
// Post-processes tsc's client compile output into the IIFE shape that
// DSH's `window.__ModuleLoader__.load(...)` expects.
//
// Pipeline:
//   1. tsc compiles src/client/api.ts → client-build/api.js (ESM, no JSX)
//   2. We read client-build/api.js, strip its `export` keywords.
//   3. We read src/client/index.js (plain JS, no imports from React).
//   4. We strip the `import { ... } from "./api.js";` line from index.js.
//   5. We prepend (2) into (3), then wrap the whole thing in:
//
//        window.__ModuleLoader__.load({
//          id: "dsh-mmw-tools",
//          factory: (require) => {
//            var module = { exports: {} };
//            var exports = module.exports;
//            let react = require("react");
//            let jsxRuntime = require("react/jsx-runtime");
//            // ... inlined source ...
//            exports.apply = apply;
//            exports.inject = inject;
//            return module.exports;
//          }
//        });
//
//   6. Output to lib/client.js.
//
// The `react` / `jsxRuntime` references inside the inlined source are
// written explicitly as `react.useState`, `jsxRuntime.jsx`, etc. —
// matching dsh-feishu-mcp's compiled client.js shape.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const API_BUILD = path.join(ROOT, "client-build", "api.js");
const PANEL_SRC = path.join(ROOT, "src", "client", "index.js");
const OUT = path.join(ROOT, "lib", "client.js");

function die(message) {
  console.error(`build-client: ${message}`);
  process.exit(1);
}

if (!existsSync(API_BUILD)) {
  die(`missing ${API_BUILD}. Run \`pnpm exec tsc -p tsconfig.client.json\` first.`);
}
if (!existsSync(PANEL_SRC)) {
  die(`missing ${PANEL_SRC}`);
}

// 1. Read api.js (tsc output) and strip `export` keywords.
//    We keep everything else so the closure references inside the
//    factory work without renaming.
const apiSource = readFileSync(API_BUILD, "utf8")
  .replace(/^export\s+/gm, "")
  .trim();

// 2. Read panel source (plain JS).
let panelSource = readFileSync(PANEL_SRC, "utf8");

// 3. Strip the `import { githubApi, GithubApiError } from "./api.js";`
//    line — the symbols it provided are now inlined above.
panelSource = panelSource.replace(
  /^\s*import\s+\{[^}]+\}\s+from\s+["']\.\/api\.js["'];?\s*$/m,
  ""
);

// 4. Strip the dangling `githubApi;` side-effect statement we added
//    at the bottom of index.js — it's now redundant.
panelSource = panelSource.replace(/^\s*\/\/ eslint-disable.*\n\s*githubApi;\s*$/m, "");

// 4b. Rewrite the trailing `export { a, b, c };` statement into
//     `exports.a = a; exports.b = b; ...`. ESM `export` doesn't work
//     inside the IIFE factory (which is plain JS).
panelSource = panelSource.replace(
  /^export\s*\{\s*([^}]+)\s*\};?[ \t]*$/gm,
  (_, names) => {
    const list = names
      .split(",")
      .map((n) => n.trim().split(/\s+as\s+/).pop())
      .filter(Boolean);
    return list.map((n) => `exports.${n} = ${n};`).join("\n");
  }
);

// 5. Wrap.
const wrapped = `// AUTO-GENERATED by scripts/build-client.mjs — do not edit.
// Source: src/client/{api.ts, index.js} (compiled by tsc + this script).

if (typeof window === "undefined" || !window.__ModuleLoader__) {
  throw new Error("dsh-mmw-tools client.js must be loaded by the DSH web __ModuleLoader__.");
}

window.__ModuleLoader__.load({
  id: "dsh-mmw-tools",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
    let react = require("react");
    let react_jsx_runtime = require("react/jsx-runtime");

    // ── inlined: client-build/api.js (api.ts compiled by tsc) ──
${apiSource
  .split("\n")
  .map((line) => "    " + line)
  .join("\n")}

    // ── inlined: src/client/index.js (panel body) ──
${panelSource
  .split("\n")
  .map((line) => "    " + line)
  .join("\n")}

    return module.exports;
  },
});
`;

// 5b. Refuse to emit a bundle that still contains ESM `export` syntax.
// A stray `export { ... }` inside the IIFE factory is a SyntaxError, and
// it fails only in the browser at load time — the build stayed green and
// the panel simply never registered. Cheaper to fail here.
const strayExport = wrapped.match(/^\s*export\s/m);
if (strayExport) {
  console.error(
    "build-client: refusing to write — ESM `export` survived inside the CJS factory.\n" +
      "The rewrite only understands `export { a, b };` on its own line."
  );
  process.exit(1);
}

// 6. Write.
writeFileSync(OUT, wrapped, "utf8");
console.log(`build-client: wrote ${OUT} (${wrapped.length} bytes)`);